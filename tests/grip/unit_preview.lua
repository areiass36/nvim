-- The pane half of the explorer: what each level of the tree says it holds.
--
-- Every case here runs against the fixture snapshot, which is the state the
-- pane is written for: a swept catalog answers synchronously, so the lines are
-- in hand the moment render returns and nothing is asked of any server. The
-- one thing these cases cannot exercise is the sample, which is a real query;
-- what they do check is the decision to take one, which is where a mistake
-- would cost a query per keystroke against a production replica.
local support = require("tests.grip.support")
local check, has, lacks = support.check, support.has, support.lacks

local grip = require("grip")
local icons = require("core.icons")
local preview = require("grip.preview")

local shop = support.swept_connection({ name = "Shop", database = "shop" })
local server = support.server_node(shop)
local public = support.child(server, "public")
local customers = support.child(public, "customers")
local orders = support.child(public, "orders")
local view = support.child(public, "active_customers")
local id = support.child(customers, "id")
local created = support.child(customers, "created_at")

support.describe("a connection")

local lines = support.pane(server)
has("names itself", lines, "-- Shop")
has("says which engine", lines, "driver      postgres")
has("and where it points", lines, "host        db.example.test:5432")
has("and which database", lines, "database    shop")
has("and who it logs in as", lines, "user        tester")
has("says whether the process is up", lines, "connected   no")
has("and what has been swept out of it", lines, "4 tables in 2 schemas, just now")
has("then lists what is inside", lines, "2 schemas")
has("one line per schema, with its icon", lines, ("%s public"):format(icons.schema))
has("including the other one", lines, ("%s audit"):format(icons.schema))

support.describe("a connection that has never been swept")

local cold = support.connection({ name = "Cold" })
local cold_lines = support.pane({
	id = "cold",
	level = "attribute",
	kind = "column",
	name = "whatever",
	ref = { server = cold.id, namespace = "public", set = "t" },
	facts = { type = "text" },
})
check("still describes what it can without asking anyone", cold_lines[1], "-- Cold/public.t.whatever")

support.describe("a database")

-- A connection that has not had its database chosen, which is the only shape
-- where a database is a level at all: with one named there is nothing to pick
-- and neogrip's tree skips straight to the schemas.
local cluster = support.connection({ name = "Cluster", database = "" })
support.sweep(cluster, "shop")
local instance = {
	id = "instance",
	level = "instance",
	kind = "database",
	name = "shop",
	ref = { server = cluster.id, instance = "shop" },
	facts = { reconnects = true },
	expandable = true,
}
lines = support.pane(instance)
has("names the walk that led to it", lines, "-- Cluster/shop")
has("says it is a database", lines, "database    shop")
has("says what is swept", lines, "4 tables in 2 schemas")
has("warns that walking in reopens the connection", lines, "walking in opens a connection of its own")
has("and lists its schemas", lines, ("%s public"):format(icons.schema))

support.describe("a schema")

lines = support.pane(public)
has("names itself", lines, "-- Shop/public")
has("counts what is in it, by kind", lines, "2 tables, 1 view")
has("lists a table with its columns", lines, ("%s customers"):format(icons.set))
has("and the remark it carries", lines, "People who buy things")
has("a view with the eye", lines, ("%s active_customers"):format(icons.view))
check("every line is a comment", (function()
	for _, line in ipairs(lines) do
		if line ~= "" and line:sub(1, 2) ~= "--" then
			return line
		end
	end
	return true
end)(), true)

support.describe("a table")

lines = support.pane(customers)
has("opens with the statement that would create it", lines, 'CREATE TABLE "public"."customers" (')
has("with the columns lined up", lines, '"email"')
has("saying what cannot be null", lines, "NOT NULL")
has("and what the server fills in", lines, "GENERATED BY DEFAULT AS IDENTITY")
has("the primary key, by name", lines, 'CONSTRAINT "customers_pkey" PRIMARY KEY ("id")')
has("the indexes, as statements", lines, 'CREATE UNIQUE INDEX "customers_email_key"')
lacks("but not the one the key already made", lines, '"customers_pkey" ON')
has("the remarks, as statements", lines, "COMMENT ON TABLE")
has("and what points at it", lines, "Referenced by (1)")

lines = support.pane(orders)
has("a foreign key is spelled out where there is one", lines, 'FOREIGN KEY ("customer_id")')
has("with what it points at", lines, 'REFERENCES "public"."customers" ("id")')
has("and what happens on delete", lines, "ON DELETE CASCADE")

lines = support.pane(view)
has("a view is drawn from what is known about it", lines, 'CREATE TABLE "public"."active_customers" (')

support.describe("rows, and when to ask for them")

-- pane_now rather than pane: a sample is a real query, so these cases read
-- what was drawn before the fetch is even scheduled and never wait for one.
preview.forget()
preview.options.sample_automatically = true
lines = support.pane_now(customers)
has("a database you can query is sampled without being asked", lines, "-- Sample (10 rows)")

preview.forget()
local replica = support.swept_connection({ name = "Replica", database = "shop", production = true })
local replica_public = support.child(support.server_node(replica), "public")
lines = support.pane_now(support.child(replica_public, "customers"))
lacks("a production database is not", lines, "-- Sample")
has("and says how to ask", lines, "production: <C-l> samples rows")

preview.forget()
lines = support.pane_now(support.child(replica_public, "customers"), { rows = true })
has("asked by hand, it samples anyway", lines, "-- Sample (10 rows)")

preview.forget()
preview.options.sample_automatically = false
lines = support.pane_now(customers)
lacks("switched off, nothing is sampled anywhere", lines, "-- Sample")

support.describe("a column")

lines = support.pane(id)
check("names the table it belongs to", lines[1], "-- Shop/public.customers.id")
has("says its type", lines, "type        bigint")
has("whether it takes a null", lines, "nullable    no")
has("whether it is the key", lines, "primary key yes")
has("and that the server numbers it", lines, "generated   by the server, on insert")

lines = support.pane(created)
has("a nullable column says so", lines, "nullable    yes")
has("a default is spelled out", lines, "default     now()")
has("and a column that is not the key says that too", lines, "primary key no")

support.describe("the way back")

lines = support.pane({ parent = true, text = ".. Schemas" })
check("describes nothing, because it is not a thing", lines, { "-- .. Schemas" })

support.describe("titles for the pane")

check("a table's pane is titled with its path", preview.title_of(customers), "Shop/public.customers")
check("a column's with its own name", preview.title_of(id), "Shop/public.customers.id")
check("a schema's with the walk", preview.title_of(public), "Shop/public")
check("the way back has no title", preview.title_of({ parent = true }), "Contents")

support.describe("remembering")

preview.forget()
local first = support.pane(public)
local again = support.pane(public)
check("a pane drawn twice is the same pane", again, first)
preview.forget()
check("until it is told to forget", #support.pane(public) > 0, true)

support.describe("a connection that is gone")

lines = support.pane({
	id = "ghost",
	level = "namespace",
	name = "public",
	ref = { server = "no-such-connection" },
	facts = {},
})
has("says so instead of raising", lines, 'no connection named "no-such-connection"')

return support
